void main() {
  group('NOAA spreadsheet port', () {
    test('matches declination, equation of time, noon, sunrise, sunset', () {
      for (final r in noaaRows) {
        final p = solarParams(r[3]);
        expect(p.declination, closeTo(r[4], 1e-9));
        expect(p.equationOfTime, closeTo(r[5], 1e-9));
        final row = spreadsheetRow(r[3], r[0], r[1], r[2]);
        expect(row.solarNoon, closeTo(r[6], 1e-11));
        expect(row.sunrise!, closeTo(r[7], 1e-11));
        expect(row.sunset!, closeTo(r[8], 1e-11));
      }
    });

    test('event-iterated sunrise is within a minute of the spreadsheet', () {
      // Year sheet, 2010-06-21 at noon: sunrise 0.2300... LST (tz -7).
      final rise = sunEvent(DateTime.utc(2010, 6, 21), 40, -105, rising: true)!;
      final set = sunEvent(DateTime.utc(2010, 6, 21), 40, -105, rising: false)!;
      // Day sheet (tz -6): sunrise 05:31:16 MDT = 11:31:16 UTC, sunset 20:32:09 MDT.
      expect(rise.difference(DateTime.utc(2010, 6, 21, 11, 31, 16)).inSeconds.abs(),
          lessThan(60));
      expect(set.difference(DateTime.utc(2010, 6, 22, 2, 32, 9)).inSeconds.abs(),
          lessThan(60));
    });
  });

  group('sun clock', () {
    const lat = 52.52, lon = 13.405; // Berlin

    test('sunrise reads 06:00 and sunset 18:00', () {
      final day = DateTime.utc(2026, 11, 8);
      final rise = sunEvent(day, lat, lon, rising: true)!;
      final set = sunEvent(day, lat, lon, rising: false)!;
      final atRise = sunClock(rise, lat, lon);
      final atSet = sunClock(set, lat, lon);
      expect(atRise.sunTime.inSeconds, closeTo(6 * 3600, 1));
      expect(atSet.sunTime.inSeconds, closeTo(18 * 3600, 1));
      final mid = rise.add(set.difference(rise) ~/ 2);
      expect(sunClock(mid, lat, lon).sunTime.inSeconds, closeTo(12 * 3600, 1));
      // November in Berlin: short day hours, long night hours.
      expect(sunClock(mid, lat, lon).realMinutesPerSunHour, lessThan(60));
    });

    test('is continuous and monotonic over two days', () {
      var t = DateTime.utc(2026, 3, 20);
      var last = sunClock(t, lat, lon).sunTime.inSeconds;
      for (var i = 0; i < 2 * 24 * 60; i++) {
        t = t.add(const Duration(minutes: 1));
        final now = sunClock(t, lat, lon).sunTime.inSeconds;
        final step = (now - last) % (24 * 3600);
        expect(step, inInclusiveRange(1, 120), reason: 'at $t');
        last = now;
      }
    });

    test('falls back to solar time in polar day', () {
      final r = sunClock(DateTime.utc(2026, 6, 21, 12), 78.22, 15.65); // Svalbard
      expect(r.mode, SunClockMode.solarTimeFallback);
      expect(r.isDay, isTrue);
    });
  });
}
